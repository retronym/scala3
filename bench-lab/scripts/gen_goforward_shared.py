"""Generates compiler/src/dotty/tools/dotc/core/GoForwardUnrolledShared.scala (DO NOT MERGE experiment): as
gen_goforward_unrolled.py, but with ONE shared, non-inlined loop head instead of a copy per step, so that each step is
just its transform. `head` returns either the final result or the version that still needs a transform; `pending`
re-checks head's transform condition to tell which (no cursor, no shared mutable state: reentrant, since `transform`
can itself call `current` on other denotations).

  python3 -I bench-lab/scripts/gen_goforward_shared.py <shape.txt>
"""
import re, sys

blocks, cur = [], None
for line in open(sys.argv[1]):
    if line.startswith("[goForwardShape]"):
        cur = []; blocks.append(cur)
    elif cur is not None and re.match(r"\d+ \S+", line):
        cur.append(line.split()[1])
shape = max(blocks, key=len)
named = lambda c: "$" not in c

out = []
w = out.append
w("""package dotty.tools.dotc
package core

import Contexts.*, Denotations.*, Periods.*, DenotTransformers.*, Decorators.*
import scala.annotation.switch

// DO NOT MERGE: GENERATED by bench-lab/scripts/gen_goforward_shared.py, do not edit.
//
// goForward unrolled over one vector of denotation transformer classes (-Ddotty.goForward=shared), like
// GoForwardUnrolled but with a single shared loop head: each step<k> is only the statically bound transform, the
// bookkeeping, a call to `head`, and a direct call to step<k+1> when the chain continues with the next transformer.
object GoForwardUnrolledShared:
  val Shape: Array[String] = Array(""")
w(",\n".join(f'    "{c}"' for c in shape))
w("""  )

  def matches(ts: Array[DenotTransformer]): Boolean =
    ts.length == Shape.length && ts.indices.forall(k => ts(k).getClass.getName == Shape(k))

  /** current, for ctx.period after self.validFor */
  def go(self: SingleDenotation, ctx: Context): SingleDenotation =
    val r = head(self, ctx)
    val nti = pending(r, ctx)
    if nti < 0 then r else dispatch(ctx.base.denotTransformerIndex(nti), r, nti, ctx)

  /** Walk to the version containing ctx.period, if any, extending the last version's validity when no transformer
   *  intervenes. Returns the result, or, if a transformer must run, the version it must run on (see `pending`).
   */
  def head(self: SingleDenotation, ctx: Context): SingleDenotation =
    val currentPeriod = ctx.period
    val valid = self.validFor
    if valid == Nowhere || valid.runId != currentPeriod.runId || !(currentPeriod > valid) then self.current(using ctx)
    else
      var cur = self
      var next = cur.nextInRun
      while next.validFor > valid && !next.validFor.contains(currentPeriod) do // existing later versions: usually none
        cur = next
        next = next.nextInRun
      if next.validFor > valid then next
      else
        val nti = ctx.base.nextDenotTransformerId(cur.validFor.lastPhaseId)
        if currentPeriod.lastPhaseId <= nti then
          cur.validFor = Period(currentPeriod.runId, cur.validFor.firstPhaseId, nti)
          go(cur, ctx)
        else cur

  /** The id of the transformer `r`, returned by `head`, still needs, or -1 if `r` is the result. This is head's own
   *  transform condition for its last version; a result never satisfies it (`current` would have transformed it).
   */
  def pending(r: SingleDenotation, ctx: Context): Int =
    val currentPeriod = ctx.period
    val valid = r.validFor
    if valid == Nowhere || valid.runId != currentPeriod.runId || !(currentPeriod > valid) || r.nextInRun.validFor > valid then -1
    else
      val nti = ctx.base.nextDenotTransformerId(valid.lastPhaseId)
      if currentPeriod.lastPhaseId <= nti then -1 else nti

  /** Bookkeeping after a transform: link `next` in and set the validity of the new current version */
  private def finish(cur: SingleDenotation, next: SingleDenotation, nti: Int, lastPid: Int, ctx: Context): SingleDenotation =
    val runId = ctx.period.runId
    if next eq cur then
      cur.validFor = Period(runId, cur.validFor.firstPhaseId, lastPid)
      cur
    else
      next.insertAfter(cur)
      next.validFor = Period(runId, nti + 1, lastPid)
      next

  def dispatch(k: Int, cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation = (k: @switch) match""")
for k, c in enumerate(shape):
    w(f"    case {k} => step{k}(cur, nti, ctx)")
w("    case _ => stepGeneric(k, cur, nti, ctx)\n")

def step(name, sig, tval, succ):
    return f"""  def {name}({sig}): SingleDenotation =
    {tval}
    val lastPid = t.lastPhaseId(using ctx)
    val savedPeriod = ctx.period
    val mutCtx = ctx.asInstanceOf[FreshContext]
    var next: SingleDenotation | Null = null
    try
      mutCtx.setPhase(t)
      next = t.transform(cur)(using ctx)
      if next ne cur then SingleDenotation.assertNotPackage(next, t, ctx)
    finally mutCtx.setPeriod(savedPeriod)
    val r = head(finish(cur, next, nti, lastPid, ctx), ctx)
    val n = pending(r, ctx)
    if n < 0 then r else {succ}dispatch(ctx.base.denotTransformerIndex(n), r, n, ctx)
"""

w(step("stepGeneric", "k: Int, cur: SingleDenotation, nti: Int, ctx: Context", "val t = ctx.base.denseDenotTransformers(k)", ""))
for k, c in enumerate(shape):
    if not named(c):
        w(f"  def step{k}(cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation = stepGeneric({k}, cur, nti, ctx)\n")
        continue
    succ = (f"if ctx.base.denotTransformerIndex(n) == {k + 1} then step{k + 1}(r, n, ctx) else "
            if k + 1 < len(shape) else "")
    w(step(f"step{k}", "cur: SingleDenotation, nti: Int, ctx: Context",
           f"val t = ctx.base.denseDenotTransformers({k}).asInstanceOf[_root_.{c}]", succ))
w("end GoForwardUnrolledShared\n")
open("compiler/src/dotty/tools/dotc/core/GoForwardUnrolledShared.scala", "w").write("\n".join(out))
print(f"{len(shape)} transformers, {sum(map(named, shape))} named")
