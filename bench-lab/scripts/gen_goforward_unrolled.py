"""Generates compiler/src/dotty/tools/dotc/core/GoForwardUnrolled.scala (DO NOT MERGE experiment): goForward
hand-unrolled over one observed vector of denotation transformer classes, as printed by
`-Ddotty.goForward.printShape` (lines `<k> <class> ...` after `[goForwardShape]`; the longest block is used).

  python3 -I bench-lab/scripts/gen_goforward_unrolled.py <shape.txt>
"""
import re, sys

blocks, cur = [], None
for line in open(sys.argv[1]):
    if line.startswith("[goForwardShape]"):
        cur = []; blocks.append(cur)
    elif cur is not None and re.match(r"\d+ \S+", line):
        cur.append(line.split()[1])
shape = max(blocks, key=len)
named = lambda c: "$" not in c  # inner classes (e.g. TerminalPhase) go through the generic step

out = []
w = out.append
w("""package dotty.tools.dotc
package core

import Contexts.*, Denotations.*, Periods.*, DenotTransformers.*, Decorators.*
import scala.annotation.switch

// DO NOT MERGE: GENERATED by bench-lab/scripts/gen_goforward_unrolled.py, do not edit.
//
// SingleDenotation.goForwardLoop hand-unrolled for one vector of denotation transformer classes
// (-Ddotty.goForward=unrolled, used only when the run's plan has exactly these classes). Each step<k> calls transform
// on the k-th transformer's class, statically bound, then runs the loop head again and, when the next transformer is
// the (k+1)-th as it is in a chain of transforms, calls step<k+1> directly: no dispatch inside a chain.
object GoForwardUnrolled:
  val Shape: Array[String] = Array(""")
w(",\n".join(f'    "{c}"' for c in shape))
w("""  )

  def matches(ts: Array[DenotTransformer]): Boolean =
    ts.length == Shape.length && ts.indices.forall(k => ts(k).getClass.getName == Shape(k))

  /** current, for ctx.period after self.validFor */
  def go(self: SingleDenotation, ctx: Context): SingleDenotation =
    head(self, ctx)((cur, nti) => dispatch(ctx.base.denotTransformerIndex(nti), cur, nti, ctx))

  /** The loop head, without a loop: walk to the containing version if any, else return what
   *  `onTransform(cur, nextTransformerId)` returns. Inline, with an inline continuation, so that each step has its own
   *  copy and its own successor call. The rare case of extending the current version's validity without a transform
   *  re-enters `go` instead of looping.
   */
  private inline def head(self: SingleDenotation, ctx: Context)(inline onTransform: (SingleDenotation, Int) => SingleDenotation): SingleDenotation =
    val currentPeriod = ctx.period
    val valid = self.validFor
    if valid == Nowhere || valid.runId != currentPeriod.runId || !(currentPeriod > valid) then self.current(using ctx)
    else
      var cur = self
      var next = cur.nextInRun
      while next.validFor > valid && !next.validFor.contains(currentPeriod) do // existing later versions: usually none
        cur = next
        next = next.nextInRun
      if next.validFor > valid then next
      else
        val nti = ctx.base.nextDenotTransformerId(cur.validFor.lastPhaseId)
        if currentPeriod.lastPhaseId <= nti then
          cur.validFor = Period(currentPeriod.runId, cur.validFor.firstPhaseId, nti)
          go(cur, ctx)
        else onTransform(cur, nti)

  /** Bookkeeping after a transform: link `next` in and set the validity of the new current version */
  private def finish(cur: SingleDenotation, next: SingleDenotation, nti: Int, lastPid: Int, ctx: Context): SingleDenotation =
    val runId = ctx.period.runId
    if next eq cur then
      cur.validFor = Period(runId, cur.validFor.firstPhaseId, lastPid)
      cur
    else
      next.insertAfter(cur)
      next.validFor = Period(runId, nti + 1, lastPid)
      next

  def dispatch(k: Int, cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation = (k: @switch) match""")
for k, c in enumerate(shape):
    w(f"    case {k} => step{k}(cur, nti, ctx)")
w("    case _ => stepGeneric(k, cur, nti, ctx)\n")
w("""  def stepGeneric(k: Int, cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation =
    val t = ctx.base.denseDenotTransformers(k)
    val lastPid = t.lastPhaseId(using ctx)
    val savedPeriod = ctx.period
    val mutCtx = ctx.asInstanceOf[FreshContext]
    var next: SingleDenotation | Null = null
    try
      mutCtx.setPhase(t)
      next = t.transform(cur)(using ctx)
      if next ne cur then SingleDenotation.assertNotPackage(next, t, ctx)
    finally mutCtx.setPeriod(savedPeriod)
    head(finish(cur, next, nti, lastPid, ctx), ctx)((c, n) => dispatch(ctx.base.denotTransformerIndex(n), c, n, ctx))
""")
for k, c in enumerate(shape):
    if not named(c):
        w(f"  def step{k}(cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation = stepGeneric({k}, cur, nti, ctx)\n")
        continue
    succ = (f"if ctx.base.denotTransformerIndex(n) == {k + 1} then step{k + 1}(c, n, ctx) else "
            if k + 1 < len(shape) else "")
    w(f"""  def step{k}(cur: SingleDenotation, nti: Int, ctx: Context): SingleDenotation =
    val t = ctx.base.denseDenotTransformers({k}).asInstanceOf[_root_.{c}]
    val lastPid = t.lastPhaseId(using ctx)
    val savedPeriod = ctx.period
    val mutCtx = ctx.asInstanceOf[FreshContext]
    var next: SingleDenotation | Null = null
    try
      mutCtx.setPhase(t)
      next = t.transform(cur)(using ctx)
      if next ne cur then SingleDenotation.assertNotPackage(next, t, ctx)
    finally mutCtx.setPeriod(savedPeriod)
    head(finish(cur, next, nti, lastPid, ctx), ctx)((c, n) => {succ}dispatch(ctx.base.denotTransformerIndex(n), c, n, ctx))
""")
w("end GoForwardUnrolled\n")
open("compiler/src/dotty/tools/dotc/core/GoForwardUnrolled.scala", "w").write("\n".join(out))
print(f"{len(shape)} transformers, {sum(map(named, shape))} named")
